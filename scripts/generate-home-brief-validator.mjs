import { readFile, writeFile } from 'node:fs/promises';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

const schemaUrl = new URL('../docs/home-brief-v0.1.schema.json', import.meta.url);
const target = new URL('../server/home-build/validate-brief.mjs', import.meta.url);
const schema = JSON.parse(await readFile(schemaUrl, 'utf8'));
const ajv = new Ajv({ strict: true, code: { esm: true, source: true } });
const validator = standaloneCode(ajv, ajv.compile(schema))
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length');
if (/require\(|new Function\(|eval\(/.test(validator)) throw Error('Unsupported validator runtime dependency.');
const code = '// Generated by scripts/generate-home-brief-validator.mjs.\n' +
  'export const homeBriefSchema = ' + JSON.stringify(schema) + ';\n' +
  'const ucs2length = value => [...value].length;\n' + validator + '\n';
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== code) throw Error('Home brief validator is out of date.');
} else {
  await writeFile(target, code);
}
